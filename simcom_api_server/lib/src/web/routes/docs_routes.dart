/// Shared 404 for every docs route when `SIMCOM_API_DOCS_ENABLED=false`.
Response _docsDisabled() {
  return Response(
    404,
    body: Body.fromString('Not found', mimeType: MimeType.plainText),
  );
}

bool _acceptsGzip(Request request) {
  final values = request.headers[HttpHeaders.acceptEncodingHeader];
  if (values == null) return false;
  return values.any((value) => value.toLowerCase().contains('gzip'));
}

Headers _assetHeaders({required bool gzipped, required String etag}) {
  return Headers.build((headers) {
    headers[HttpHeaders.varyHeader] = ['Accept-Encoding'];
    headers[HttpHeaders.cacheControlHeader] = ['public, max-age=300'];
    headers[HttpHeaders.etagHeader] = [etag];
    if (gzipped) {
      headers[HttpHeaders.contentEncodingHeader] = ['gzip'];
    }
  });
}

String _etag(Uint8List data) => '"${sha1.hex(data)}"';

bool _isNotModified(Request request, String etag) {
  final values = request.headers[HttpHeaders.ifNoneMatchHeader];
  if (values == null) return false;
  return values
      .expand((value) => value.split(','))
      .map((value) => value.trim())
      .any((value) => value == etag);
}

Uint8List _gzip(Uint8List data) {
  return Uint8List.fromList(gzip.encode(data));
}

/// `GET /docs`
///
/// Server-renders the Jaspr API explorer. The rendered page is static, so it is
/// cached after the first request.
class DocsRoute extends Route {
  DocsRoute(this.enabled) : super(methods: {Method.get});

  final bool enabled;

  static Future<Uint8List>? _cachedPage;
  Uint8List? _gzippedPage;

  Future<Uint8List> _page() async {
    final cached = _cachedPage;
    if (cached != null) return cached;

    final future = renderDocsPage();
    _cachedPage = future;
    try {
      return await future;
    } on Object {
      // Do not cache a failed render; a later request can retry.
      _cachedPage = null;
      rethrow;
    }
  }

  @override
  FutureOr<Result> handleCall(Session session, Request request) async {
    if (!enabled) return _docsDisabled();
    final body = await _page();
    final gzipped = _acceptsGzip(request);
    final payload = gzipped ? (_gzippedPage ??= _gzip(body)) : body;
    final etag = _etag(payload);
    if (_isNotModified(request, etag)) {
      return Response(
        304,
        headers: _assetHeaders(gzipped: gzipped, etag: etag),
      );
    }
    return Response(
      200,
      body: Body.fromData(payload, mimeType: MimeType.html),
      headers: _assetHeaders(gzipped: gzipped, etag: etag),
    );
  }
}

/// `GET /docs/style.css`
class DocsStyleRoute extends Route {
  DocsStyleRoute(this.enabled) : super(methods: {Method.get});

  final bool enabled;

  static final Uint8List _body = Uint8List.fromList(utf8.encode(docsCss));
  static final Uint8List _gzippedBody = _gzip(_body);
  static final String _etagValue = _etag(_body);
  static final String _gzippedEtagValue = _etag(_gzippedBody);

  @override
  FutureOr<Result> handleCall(Session session, Request request) {
    if (!enabled) return _docsDisabled();
    final gzipped = _acceptsGzip(request);
    final etag = gzipped ? _gzippedEtagValue : _etagValue;
    if (_isNotModified(request, etag)) {
      return Response(
        304,
        headers: _assetHeaders(gzipped: gzipped, etag: etag),
      );
    }
    return Response(
      200,
      body: Body.fromData(
        gzipped ? _gzippedBody : _body,
        mimeType: MimeType.css,
      ),
      headers: _assetHeaders(gzipped: gzipped, etag: etag),
    );
  }
}

/// `GET /docs/app.js`
///
/// Serves the browser bundle compiled from `docs_app.client.dart`. The bundle
/// is generated by `dart run tool/build_docs_client.dart`; when it is missing
/// the server-rendered page is still available but read-only.
class DocsScriptRoute extends Route {
  DocsScriptRoute(
    this.enabled, {
    Future<Uint8List?> Function()? loader,
  }) : _loader = loader ?? loadDocsClientBundle,
       super(methods: {Method.get});

  final bool enabled;
  final Future<Uint8List?> Function() _loader;

  Future<Uint8List?>? _cached;
  Uint8List? _gzipped;
  String? _etagValue;
  String? _gzippedEtagValue;
  bool _reportedMissing = false;

  Future<Uint8List?> _bundle() async {
    final cached = _cached;
    if (cached != null) return cached;
    final future = _loader();
    _cached = future;
    final result = await future;
    // Do not cache a missing bundle forever; a later request may see the file
    // after `tool/build_docs_client.dart` has run.
    if (result == null) _cached = null;
    return result;
  }

  @override
  FutureOr<Result> handleCall(Session session, Request request) async {
    if (!enabled) return _docsDisabled();

    Uint8List? body;
    try {
      body = await _bundle();
    } on Object catch (error, stackTrace) {
      if (!_reportedMissing) {
        _reportedMissing = true;
        AppLog.warning(
          'Could not read the docs client bundle: $error',
          name: 'simcom_api.docs',
          error: error,
          stackTrace: stackTrace,
        );
      }
      // Let the next request retry after a transient read failure.
      _cached = null;
    }

    if (body == null) {
      if (!_reportedMissing) {
        _reportedMissing = true;
        AppLog.warning(
          'Docs client bundle not found. Run '
          '`dart run tool/build_docs_client.dart` in simcom_api_server.',
          name: 'simcom_api.docs',
        );
      }
      return Response(
        503,
        body: Body.fromString(
          'The docs client bundle is not built. Run '
          '`dart run tool/build_docs_client.dart` in simcom_api_server.',
          mimeType: MimeType.plainText,
        ),
      );
    }

    final gzipped = _acceptsGzip(request);
    final payload = gzipped ? (_gzipped ??= _gzip(body)) : body;
    final etag = gzipped
        ? (_gzippedEtagValue ??= _etag(payload))
        : (_etagValue ??= _etag(payload));
    if (_isNotModified(request, etag)) {
      return Response(
        304,
        headers: _assetHeaders(gzipped: gzipped, etag: etag),
      );
    }
    return Response(
      200,
      body: Body.fromData(payload, mimeType: MimeType.javascript),
      headers: _assetHeaders(gzipped: gzipped, etag: etag),
    );
  }
}

/// `GET /openapi.json`
class OpenApiRoute extends Route {
  OpenApiRoute(this.enabled) : super(methods: {Method.get});

  final bool enabled;

  static final Uint8List _body = Uint8List.fromList(
    utf8.encode(buildOpenApiJson()),
  );
  static final String _etagValue = _etag(_body);

  @override
  FutureOr<Result> handleCall(Session session, Request request) {
    if (!enabled) return _docsDisabled();
    if (_isNotModified(request, _etagValue)) {
      return Response(
        304,
        headers: _assetHeaders(gzipped: false, etag: _etagValue),
      );
    }
    return Response(
      200,
      body: Body.fromData(_body, mimeType: MimeType.json),
      headers: _assetHeaders(gzipped: false, etag: _etagValue),
    );
  }
}
