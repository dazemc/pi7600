import 'dart:io';
import 'dart:math' as math;
import 'dart:typed_data';

/// A detected face and its embedding, produced by a recognition backend.
class DetectedFace {
  const DetectedFace({
    required this.x,
    required this.y,
    required this.width,
    required this.height,
    required this.embedding,
  });

  final int x;
  final int y;
  final int width;
  final int height;
  final Float32List embedding;
}

/// Pluggable face detection and embedding backend.
///
/// The previous Python service used OpenCV's YuNet detector and SFace
/// recognizer. Those models are ONNX files; a backend can be supplied by an
/// embedding application without changing the rest of the service.
abstract interface class RecognitionBackend {
  bool get isReady;

  List<DetectedFace> detect(Uint8List jpeg);
}

/// Loads model metadata and known embeddings.
///
/// Recognition was constructed but never invoked by any route in the Python
/// service. The Dart port keeps the same lifecycle: [initialize] loads the
/// configured models and embeddings, and reports whether a backend is
/// available. No route depends on it, so a missing model or native backend only
/// disables recognition instead of failing startup.
class FacialRecognition {
  FacialRecognition({
    required this.detectorPath,
    required this.recognizerPath,
    required this.embeddingsDirectory,
    this.threshold = 0.363,
    this.backend,
  });

  final String detectorPath;
  final String recognizerPath;
  final String embeddingsDirectory;
  final double threshold;
  final RecognitionBackend? backend;

  final Map<String, Float32List> _knownFaces = {};

  bool _enabled = false;

  bool get enabled => _enabled;

  Map<String, Float32List> get knownFaces => Map.unmodifiable(_knownFaces);

  Future<void> initialize() async {
    final detector = File(detectorPath);
    final recognizer = File(recognizerPath);
    if (!detector.existsSync() || !recognizer.existsSync()) {
      _enabled = false;
      return;
    }
    if (backend?.isReady != true) {
      _enabled = false;
      return;
    }
    await _loadKnownFaces();
    _enabled = true;
  }

  Future<void> _loadKnownFaces() async {
    _knownFaces.clear();
    final directory = Directory(embeddingsDirectory);
    if (!await directory.exists()) return;

    await for (final entity in directory.list()) {
      if (entity is! File || !entity.path.endsWith('.npy')) continue;
      try {
        final bytes = await entity.readAsBytes();
        final embedding = _parseNpyFloat32(bytes);
        if (embedding == null) continue;
        final name = entity.uri.pathSegments.last.replaceAll('.npy', '');
        _knownFaces[name] = embedding;
      } on Object {
        // A malformed embedding only disables that identity.
      }
    }
  }

  List<DetectedFace> detect(Uint8List jpeg) {
    if (!_enabled) return const [];
    return backend?.detect(jpeg) ?? const [];
  }

  /// Match [embedding] against the known faces using cosine similarity.
  String identify(Float32List embedding) {
    var bestName = 'Unknown';
    var bestScore = -1.0;
    final norm = _norm(embedding);
    if (norm == 0) return bestName;

    for (final entry in _knownFaces.entries) {
      final knownNorm = _norm(entry.value);
      if (knownNorm == 0) continue;
      final score = _dot(embedding, entry.value) / (norm * knownNorm);
      if (score > bestScore) {
        bestScore = score;
        bestName = entry.key;
      }
    }
    return bestScore >= threshold ? bestName : 'Unknown';
  }

  static double _dot(Float32List a, Float32List b) {
    final length = math.min(a.length, b.length);
    var sum = 0.0;
    for (var index = 0; index < length; index++) {
      sum += a[index] * b[index];
    }
    return sum;
  }

  static double _norm(Float32List values) {
    var sum = 0.0;
    for (final value in values) {
      sum += value * value;
    }
    return math.sqrt(sum);
  }

  /// Parse the subset of the NumPy `.npy` format used by OpenCV embeddings.
  ///
  /// Only version 1.0 headers with a little-endian float32 payload are
  /// supported, which is what `numpy.save` produces for the embeddings
  /// generated by the previous service.
  static Float32List? _parseNpyFloat32(Uint8List bytes) {
    if (bytes.length < 10) return null;
    if (bytes[0] != 0x93 ||
        bytes[1] != 0x4E ||
        bytes[2] != 0x55 ||
        bytes[3] != 0x4D ||
        bytes[4] != 0x50 ||
        bytes[5] != 0x59) {
      return null;
    }
    final major = bytes[6];
    if (major != 1 && major != 2) return null;

    final headerLength = major == 1
        ? (bytes[8] | (bytes[9] << 8))
        : (bytes[8] | (bytes[9] << 8) | (bytes[10] << 16) | (bytes[11] << 24));
    final headerStart = major == 1 ? 10 : 12;
    final dataStart = headerStart + headerLength;
    if (dataStart > bytes.length) return null;

    final header = String.fromCharCodes(
      bytes.sublist(headerStart, dataStart),
    );
    if (!header.contains('<f4') && !header.contains('|f4')) return null;

    final payload = bytes.sublist(dataStart);
    if (payload.length % 4 != 0) return null;
    final result = Float32List(payload.length ~/ 4);
    final view = ByteData.sublistView(payload);
    for (var index = 0; index < result.length; index++) {
      result[index] = view.getFloat32(index * 4, Endian.little);
    }
    return result;
  }
}
